class UNetFPNDecoder_DS_Attn(nn.Module):

    def __init__(self,
                 fuse_dim=128,
                 out_classes=1,
                 use_deep_supervision=True):

        super().__init__()

        C = fuse_dim

        self.use_deep_supervision = use_deep_supervision

        # -------------------------------------------------
        # Attention Gates
        # -------------------------------------------------

        self.gate32_16 = AttentionGate(C, C, C // 2)
        self.gate16_8  = AttentionGate(C, C, C // 2)
        self.gate8_4   = AttentionGate(C, C, C // 2)

        # -------------------------------------------------
        # Decoder Blocks
        # (Concat -> NABlock -> 1x1 Conv)
        # -------------------------------------------------

        self.na32_16 = NABlock(2 * C)
        self.na16_8  = NABlock(2 * C)
        self.na8_4   = NABlock(2 * C)

        self.reduce32_16 = nn.Conv2d(2 * C, C, kernel_size=1)
        self.reduce16_8  = nn.Conv2d(2 * C, C, kernel_size=1)
        self.reduce8_4   = nn.Conv2d(2 * C, C, kernel_size=1)

        # -------------------------------------------------
        # ASPP
        # -------------------------------------------------

        self.aspp = ASPP(C, C)

        # -------------------------------------------------
        # Prediction Head
        # -------------------------------------------------

        self.head = nn.Conv2d(
            C,
            out_classes,
            kernel_size=1
        )

        # -------------------------------------------------
        # Deep Supervision
        # -------------------------------------------------

        if self.use_deep_supervision:

            self.ds16 = nn.Conv2d(
                C,
                out_classes,
                kernel_size=1
            )

            self.ds8 = nn.Conv2d(
                C,
                out_classes,
                kernel_size=1
            )

    def forward(self, feats):

        F4, F8, F16, F32 = feats

        # =================================================
        # Stage 32 -> 16
        # =================================================

        x = F.interpolate(
            F32,
            size=F16.shape[-2:],
            mode="bilinear",
            align_corners=False
        )

        G16 = self.gate32_16(F16, x)

        x = torch.cat([x, G16], dim=1)

        x = self.na32_16(x)

        x = self.reduce32_16(x)

        DS16 = x

        # =================================================
        # Stage 16 -> 8
        # =================================================

        x = F.interpolate(
            x,
            size=F8.shape[-2:],
            mode="bilinear",
            align_corners=False
        )

        G8 = self.gate16_8(F8, x)

        x = torch.cat([x, G8], dim=1)

        x = self.na16_8(x)

        x = self.reduce16_8(x)

        DS8 = x

        # =================================================
        # Stage 8 -> 4
        # =================================================

        x = F.interpolate(
            x,
            size=F4.shape[-2:],
            mode="bilinear",
            align_corners=False
        )

        G4 = self.gate8_4(F4, x)

        x = torch.cat([x, G4], dim=1)

        x = self.na8_4(x)

        x = self.reduce8_4(x)

        # =================================================
        # ASPP
        # =================================================

        x = self.aspp(x)

        # =================================================
        # Prediction
        # =================================================

        logits = self.head(x)

        if self.use_deep_supervision:

            ds16 = self.ds16(DS16)

            ds8 = self.ds8(DS8)

            return logits, ds16, ds8

        return logits