class NABlock(nn.Module):
    """DW 3x3 + PW 1x1 + GN + GELU + SE."""
    def __init__(self, dim):
        super().__init__()
        self.dw = nn.Conv2d(dim, dim, 3, padding=1, groups=dim, bias=False)
        self.pw = nn.Conv2d(dim, dim, 1, bias=False)
        self.gn = nn.GroupNorm(8, dim)
        self.act = nn.GELU()
        self.se = nn.Sequential(
               nn.AdaptiveAvgPool2d(1),
               nn.Conv2d(dim, dim // reduction, 1),
               nn.GELU(),
               nn.Conv2d(dim // reduction, dim, 1),
               nn.Sigmoid()
               )
    def forward(self, x):
        y = self.dw(x)
        y = self.pw(y)
        y = self.gn(y)
        y = self.act(y)
        y = y * self.se(y)
        return y


class AttentionGate(nn.Module):

    def __init__(self, in_ch_skip, in_ch_g, inter_ch):
        super().__init__()

        self.theta = nn.Conv2d(
            in_ch_skip,
            inter_ch,
            kernel_size=1,
            bias=True
        )

        self.phi = nn.Conv2d(
            in_ch_g,
            inter_ch,
            kernel_size=1,
            bias=True
        )

        self.psi = nn.Conv2d(
            inter_ch,
            1,
            kernel_size=1,
            bias=True
        )

        self.relu = nn.ReLU(inplace=True)
        self.sigmoid = nn.Sigmoid()

    def forward(self, x_skip, g):

        q = self.theta(x_skip) + self.phi(g)

        q = self.relu(q)

        alpha = self.sigmoid(self.psi(q))

        return x_skip * alpha

class ASPP(nn.Module):
    def __init__(self, in_ch, out_ch, rates=(1, 6, 12, 18)):
        super().__init__()

        # Multi-scale atrous branches
        self.branches = nn.ModuleList([
            nn.Conv2d(in_ch, out_ch, kernel_size=1, bias=False)
        ])

        for r in rates[1:]:
            self.branches.append(
                nn.Conv2d(
                    in_ch,
                    out_ch,
                    kernel_size=3,
                    padding=r,
                    dilation=r,
                    bias=False
                )
            )

        # Image-level pooling branch
        self.image_pool = nn.Sequential(
            nn.AdaptiveAvgPool2d(1),
            nn.Conv2d(in_ch, out_ch, kernel_size=1, bias=False)
        )

        # Feature compression (1×1 Conv)
        self.project = nn.Conv2d(
            out_ch * (len(self.branches) + 1),
            out_ch,
            kernel_size=1,
            bias=False
        )

    def forward(self, x):

        feats = [branch(x) for branch in self.branches]

        img = self.image_pool(x)
        img = F.interpolate(
            img,
            size=x.shape[-2:],
            mode='bilinear',
            align_corners=False
        )

        feats.append(img)

        x = torch.cat(feats, dim=1)

        x = self.project(x)

        return x

