class HybridEncoder(nn.Module):
    """
    Hybrid CNN-Transformer encoder.

    Output:
        F4, F8, F16, F32
    """

    def __init__(
        self,
        backbone_name="nvidia/mit-b5",
        fuse_dim=128,
        pretrained=True,
    ):
        super().__init__()

        # -------------------------------------------------
        # Transformer Branch (SegFormer-B5)
        # -------------------------------------------------
        if pretrained:
            self.segformer = SegformerModel.from_pretrained(
                backbone_name,
                output_hidden_states=True
            )
        else:
            cfg = AutoConfig.from_pretrained(backbone_name)
            cfg.output_hidden_states = True
            self.segformer = SegformerModel(cfg)

        # -------------------------------------------------
        # CNN Branch (ResNet-50)
        # -------------------------------------------------
        resnet = models.resnet50(
            weights=models.ResNet50_Weights.IMAGENET1K_V2
            if pretrained else None
        )

        self.conv1 = nn.Sequential(
            resnet.conv1,
            resnet.bn1,
            resnet.relu
        )

        self.pool = resnet.maxpool

        self.layer1 = resnet.layer1
        self.layer2 = resnet.layer2
        self.layer3 = resnet.layer3
        self.layer4 = resnet.layer4

        # -------------------------------------------------
        # Feature Projection
        # -------------------------------------------------

        self.proj_trans = nn.ModuleList([
            nn.Conv2d(64, fuse_dim, kernel_size=1),
            nn.Conv2d(128, fuse_dim, kernel_size=1),
            nn.Conv2d(320, fuse_dim, kernel_size=1),
            nn.Conv2d(512, fuse_dim, kernel_size=1),
        ])

        self.proj_cnn = nn.ModuleList([
            nn.Conv2d(256, fuse_dim, kernel_size=1),
            nn.Conv2d(512, fuse_dim, kernel_size=1),
            nn.Conv2d(1024, fuse_dim, kernel_size=1),
            nn.Conv2d(2048, fuse_dim, kernel_size=1),
        ])

        fusion_channels = fuse_dim * 2

        # -------------------------------------------------
        # Stage-wise Feature Fusion
        # -------------------------------------------------

        self.na_blocks = nn.ModuleList([
            NABlock(fusion_channels)
            for _ in range(4)
        ])

        self.fuse_conv = nn.ModuleList([
            nn.Conv2d(
                fusion_channels,
                fuse_dim,
                kernel_size=1
            )
            for _ in range(4)
        ])

        self.strides = [4, 8, 16, 32]

        self.transformer_dims = [64, 128, 320, 512]

    @staticmethod
    def reshape_tokens(tokens, B, H, W, C):
        return tokens.transpose(1, 2).reshape(B, C, H, W)

    def transformer_features(self, x):

        B, _, H, W = x.shape

        outputs = self.segformer(pixel_values=x)

        hidden_states = list(outputs.hidden_states)

        T_features = []

        for i, stride in enumerate(self.strides):

            Hi = H // stride
            Wi = W // stride

            T_features.append(
                self.reshape_tokens(
                    hidden_states[i],
                    B,
                    Hi,
                    Wi,
                    self.transformer_dims[i]
                )
            )

        return T_features

    def forward(self, x):

        # -------------------------------------------------
        # Transformer Branch
        # -------------------------------------------------

        T1, T2, T3, T4 = self.transformer_features(x)

        # -------------------------------------------------
        # CNN Branch
        # -------------------------------------------------

        x = self.conv1(x)
        x = self.pool(x)

        R1 = self.layer1(x)
        R2 = self.layer2(R1)
        R3 = self.layer3(R2)
        R4 = self.layer4(R3)

        transformer_features = [T1, T2, T3, T4]
        cnn_features = [R1, R2, R3, R4]

        fused_features = []

        # -------------------------------------------------
        # Projection
        # → Concatenation
        # → NABlock
        # → 1×1 Compression
        # -------------------------------------------------

        for i in range(4):

            P_trans = self.proj_trans[i](transformer_features[i])

            P_cnn = self.proj_cnn[i](cnn_features[i])

            F = torch.cat([P_trans, P_cnn], dim=1)

            F = self.na_blocks[i](F)

            F = self.fuse_conv[i](F)

            fused_features.append(F)

        F4, F8, F16, F32 = fused_features

        return [F4, F8, F16, F32]

